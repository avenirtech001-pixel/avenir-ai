import React, { useState } from 'react';
import { useCodex } from '../../context/CodexContext';
import { 
  FolderTree, 
  FileCode, 
  Terminal, 
  Play, 
  Copy, 
  Check, 
  Plus, 
  Search, 
  Save, 
  Sparkles,
  ChevronRight,
  ChevronDown,
  Layers,
  FilePlus2,
  Trash2
} from 'lucide-react';

export const VSCodeWorkspace: React.FC = () => {
  const { 
    files, 
    activeFilePath, 
    setActiveFilePath, 
    updateFileContent, 
    createFile,
    terminalHistory, 
    runTerminalCommand,
    sendMessage,
    isGenerating
  } = useCodex();

  const [terminalInput, setTerminalInput] = useState('');
  const [copied, setCopied] = useState(false);
  const [isTerminalOpen, setIsTerminalOpen] = useState(true);
  const [searchQuery, setSearchQuery] = useState('');

  const activeFile = files[activeFilePath] || Object.values(files)[0];

  const handleCopyCode = () => {
    if (!activeFile) return;
    navigator.clipboard.writeText(activeFile.content);
    setCopied(true);
    setTimeout(() => setCopied(false), 1500);
  };

  const handleTerminalSubmit = (e: React.FormEvent) => {
    e.preventDefault();
    if (!terminalInput.trim()) return;
    runTerminalCommand(terminalInput.trim());
    setTerminalInput('');
  };

  const handleNewFile = () => {
    const filename = prompt('Enter new file path (e.g. src/utils/math.ts):');
    if (filename) {
      createFile(filename, 'typescript', 'vscode', '// Generated by Codex\n');
    }
  };

  const filteredFiles = Object.keys(files).filter((p) =>
    p.toLowerCase().includes(searchQuery.toLowerCase())
  );

  return (
    <div className="flex h-full bg-[#0a0c10] text-zinc-200 select-none overflow-hidden">
      {/* File Explorer Sidebar */}
      <div className="w-56 border-r border-zinc-800/80 bg-[#0e1117] flex flex-col shrink-0">
        <div className="h-9 px-3 border-b border-zinc-800/80 flex items-center justify-between text-xs font-semibold text-zinc-400 uppercase tracking-wider">
          <div className="flex items-center gap-1.5">
            <FolderTree className="h-3.5 w-3.5 text-blue-400" />
            <span>Explorer</span>
          </div>
          <button
            onClick={handleNewFile}
            title="Create File"
            className="p-1 rounded hover:bg-zinc-800 text-zinc-400 hover:text-white transition-colors"
          >
            <FilePlus2 className="h-3.5 w-3.5" />
          </button>
        </div>

        {/* Search Input */}
        <div className="p-2 border-b border-zinc-800/60">
          <div className="relative">
            <Search className="h-3 w-3 absolute left-2 top-2 text-zinc-500" />
            <input
              type="text"
              placeholder="Search files..."
              value={searchQuery}
              onChange={(e) => setSearchQuery(e.target.value)}
              className="w-full bg-[#080a0d] border border-zinc-800 rounded px-2 py-1 pl-7 text-[11px] text-zinc-200 outline-none focus:border-blue-500/50"
            />
          </div>
        </div>

        {/* Files Tree */}
        <div className="flex-1 overflow-y-auto p-1 text-xs space-y-0.5">
          <div className="px-2 py-1 text-[10px] uppercase font-bold text-zinc-500 tracking-wider">
            Workspace Files
          </div>
          {filteredFiles.map((path) => {
            const file = files[path];
            const isSelected = activeFilePath === path;

            return (
              <button
                key={path}
                onClick={() => setActiveFilePath(path)}
                className={`w-full flex items-center justify-between px-2.5 py-1.5 rounded text-left transition-colors font-mono text-[11px] ${
                  isSelected
                    ? 'bg-blue-600/15 text-blue-300 border border-blue-500/20'
                    : 'text-zinc-400 hover:text-zinc-200 hover:bg-zinc-800/50'
                }`}
              >
                <div className="flex items-center gap-1.5 truncate">
                  <FileCode className={`h-3.5 w-3.5 shrink-0 ${isSelected ? 'text-blue-400' : 'text-zinc-500'}`} />
                  <span className="truncate">{file?.name || path}</span>
                </div>
                {file?.isModified && (
                  <span className="h-1.5 w-1.5 rounded-full bg-blue-400 shrink-0" />
                )}
              </button>
            );
          })}
        </div>
      </div>

      {/* Editor & Terminal Area */}
      <div className="flex-1 flex flex-col min-w-0 bg-[#0d0f14]">
        {/* Editor Tab Bar */}
        <div className="h-9 border-b border-zinc-800/80 bg-[#0e1117] flex items-center justify-between px-2 overflow-x-auto shrink-0">
          <div className="flex items-center gap-1">
            {activeFile && (
              <div className="flex items-center gap-2 px-3 py-1 bg-[#0a0c10] border-t-2 border-t-blue-500 border-x border-zinc-800/80 text-xs font-mono text-zinc-200 rounded-t">
                <FileCode className="h-3.5 w-3.5 text-blue-400" />
                <span>{activeFile.name}</span>
                <span className="text-[10px] px-1 rounded bg-zinc-800 text-zinc-400 uppercase font-sans">
                  {activeFile.language}
                </span>
              </div>
            )}
          </div>

          <div className="flex items-center gap-1.5">
            <button
              onClick={() => sendMessage(`Please review and optimize the code in ${activeFile?.path}`)}
              disabled={isGenerating || !activeFile}
              className="flex items-center gap-1 px-2.5 py-1 rounded bg-zinc-800 hover:bg-zinc-700/80 text-zinc-300 text-xs font-medium transition-colors"
            >
              <Sparkles className="h-3 w-3 text-emerald-400" />
              <span>Optimize with Codex</span>
            </button>
            <button
              onClick={handleCopyCode}
              className="p-1.5 rounded hover:bg-zinc-800 text-zinc-400 hover:text-zinc-200 transition-colors"
              title="Copy code"
            >
              {copied ? <Check className="h-3.5 w-3.5 text-emerald-400" /> : <Copy className="h-3.5 w-3.5" />}
            </button>
          </div>
        </div>

        {/* Code Content Area */}
        <div className="flex-1 relative overflow-auto font-mono text-xs flex">
          {/* Line Numbers */}
          <div className="w-12 py-3 bg-[#0a0c10] border-r border-zinc-900 text-zinc-600 text-right pr-3 select-none shrink-0 font-mono text-[11px] leading-5">
            {activeFile?.content.split('\n').map((_, idx) => (
              <div key={idx}>{idx + 1}</div>
            ))}
          </div>

          {/* Editable Text Area */}
          <textarea
            value={activeFile?.content || ''}
            onChange={(e) => updateFileContent(activeFile.path, e.target.value)}
            spellCheck={false}
            className="flex-1 w-full bg-transparent p-3 text-zinc-200 font-mono text-[11px] sm:text-xs leading-5 outline-none resize-none whitespace-pre overflow-auto"
          />
        </div>

        {/* Integrated Terminal */}
        <div className={`border-t border-zinc-800/80 bg-[#080a0d] flex flex-col transition-all ${isTerminalOpen ? 'h-48' : 'h-8'} shrink-0`}>
          <div className="h-8 px-3 border-b border-zinc-800/60 bg-[#0e1117] flex items-center justify-between text-xs font-semibold text-zinc-400">
            <button
              onClick={() => setIsTerminalOpen(!isTerminalOpen)}
              className="flex items-center gap-1.5 hover:text-zinc-200"
            >
              <Terminal className="h-3.5 w-3.5 text-blue-400" />
              <span className="font-mono text-[11px]">BASH TERMINAL (Codex Daemon)</span>
              {isTerminalOpen ? <ChevronDown className="h-3 w-3" /> : <ChevronRight className="h-3 w-3" />}
            </button>
            <div className="flex items-center gap-2 text-[10px] text-zinc-500 font-mono">
              <span>Exit Code: 0</span>
              <button
                onClick={() => runTerminalCommand('clear')}
                className="hover:text-zinc-300 transition-colors"
              >
                Clear
              </button>
            </div>
          </div>

          {isTerminalOpen && (
            <div className="flex-1 flex flex-col overflow-hidden p-2">
              <div className="flex-1 overflow-y-auto space-y-1 font-mono text-[11px] text-zinc-300 px-1">
                {terminalHistory.map((line, idx) => (
                  <div key={idx} className={line.startsWith('$') ? 'text-emerald-400 font-semibold' : 'text-zinc-400'}>
                    {line}
                  </div>
                ))}
              </div>

              {/* Terminal Command Input */}
              <form onSubmit={handleTerminalSubmit} className="flex items-center gap-2 pt-1 border-t border-zinc-900 mt-1">
                <span className="font-mono text-emerald-400 text-xs">$</span>
                <input
                  type="text"
                  placeholder="Type npm test, gradlew assemble, mt5 backtest, or ls..."
                  value={terminalInput}
                  onChange={(e) => setTerminalInput(e.target.value)}
                  className="flex-1 bg-transparent font-mono text-[11px] text-zinc-100 outline-none placeholder:text-zinc-700"
                />
              </form>
            </div>
          )}
        </div>
      </div>
    </div>
  );
};
